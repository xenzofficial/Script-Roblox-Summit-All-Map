    BtnHide.Text = hideEnabled and "🚫 HIDE P: ON" or "🚫 HIDE P: OFF"
    BtnHide.BackgroundColor3 = hideEnabled and Color3.fromRGB(40, 140, 70) or Color3.fromRGB(150, 50, 50)
    updateHide()
    if hideEnabled then hideConn = RunService.Heartbeat:Connect(updateHide) else if hideConn then hideConn:Disconnect() end updateHide() end
end)

